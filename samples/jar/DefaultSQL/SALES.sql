SELECT BKARHINV.BKAR_INV_CUSNME, BKARHINV.BKAR_INV_CUSCOD, BKARHINV.BKAR_INV_INVDTE, 
       BKARHIVL.BKAR_INVL_PCODE, BKARHIVL.BKAR_INVL_PDESC, BKARHIVL.BKAR_INVL_PQTY, 
       BKARHIVL.BKAR_INVL_PPRCE, BKARHIVL.BKAR_INVL_PCOGS, BKARHIVL.BKAR_INVL_ASD
FROM   BKARHINV, BKARHIVL
WHERE  BKARHINV.BKAR_INV_NUM = BKARHIVL.BKAR_INVL_INVNM
AND    BKARHIVL.BKAR_INVL_PCODE <> ''
AND BKARHIVL.BKAR_INVL_ASD >='2012-01-01'
ORDER BY BKARHINV.BKAR_INV_CUSCOD ASC
