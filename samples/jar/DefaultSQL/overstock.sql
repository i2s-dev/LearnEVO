SELECT BKICMSTR.BKIC_PROD_CODE as 'Item', 
       BKICMSTR.BKIC_PROD_DESC as 'Desc', 
       BKICMSTR.BKIC_PROD_AVGC as 'Unit Cost', 
       MTICMSTR.MTIC_PROD_AVAIL as 'Excess', 
       (BKICMSTR.BKIC_PROD_AVGC * MTICMSTR.MTIC_PROD_AVAIL) as 'Value',
       BKICMSTR.BKIC_PROD_UOO as 'On PO', 
       BKICMSTR.BKIC_PROD_UOH as 'On Hand', 
       MTICMSTR.MTIC_PROD_UOA as 'Allocated',
       MTICMSTR.MTIC_PROD_VEND_1 as 'Vendor',
       BKICMSTR.BKIC_PROD_CAT as 'Cat'
FROM   BKICMSTR, MTICMSTR
WHERE  BKICMSTR.BKIC_PROD_CODE = MTICMSTR.MTIC_PROD_CODE
AND    BKICMSTR.BKIC_PROD_AVGC > 0
AND    MTICMSTR.MTIC_PROD_AVAIL > 0
