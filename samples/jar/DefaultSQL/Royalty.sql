SELECT BKARHINV.BKAR_INV_NUM, BKARHINV.BKAR_INV_SONUM, BKARHINV.BKAR_INV_DESC, 
       BKICMSTR.BKIC_PROD_CAT, BKICMSTR.BKIC_PROD_NOTE, BKARHIVL.BKAR_INVL_PEXT, 
       BKARHIVL.BKAR_INVL_PCODE, BKARHIVL.BKAR_INVL_PDESC, BKARHIVL.BKAR_INVL_PQTY,
       MTICMSTR.MTIC_PROD_SPECS_5
FROM   BKARHINV, BKICMSTR, BKARHIVL,MTICMSTR
WHERE  BKARHINV.BKAR_INV_NUM = BKARHIVL.BKAR_INVL_INVNM
AND    BKICMSTR.BKIC_PROD_CODE = MTICMSTR.MTIC_PROD_CODE 
AND    BKICMSTR.BKIC_PROD_CODE = BKARHIVL.BKAR_INVL_PCODE
AND    BKARHINV.BKAR_INV_INVDTE > '2022-01-01'
AND    BKARHINV.BKAR_INV_INVDTE < '2023-06-30'
ORDER BY BKARHINV.BKAR_INV_NUM ASC, BKARHINV.BKAR_INV_SONUM ASC, 
         BKARHIVL.BKAR_INVL_PEXT ASC
