SELECT WOBOM.WOBOM_WOPRE, WOBOM.WOBOM_WOSUF, 
       WOBOM.WOBOM_COMPCODE, WOBOM.WOBOM_COMPDESC, 
       WOBOM."WOBOM_^ISSUED" as '% Issued', ISWOEX.IS_WOEX_CDATE
FROM   WOBOM, WORKORD, ISWOEX
WHERE  WOBOM.WOBOM_WOPRE = WORKORD.MTWO_WIP_WOPRE
AND    WOBOM.WOBOM_WOSUF = WORKORD.MTWO_WIP_WOSUF
AND    ISWOEX.IS_WOEX_WOPRE = WORKORD.MTWO_WIP_WOPRE
AND    ISWOEX.IS_WOEX_WOSUF = WORKORD.MTWO_WIP_WOSUF
AND    WOBOM."WOBOM_^ISSUED" < 100
AND    WORKORD.MTWO_WIP_STATUS = 'R'
ORDER BY WOBOM.WOBOM_WOPRE ASC, WOBOM.WOBOM_WOSUF ASC
