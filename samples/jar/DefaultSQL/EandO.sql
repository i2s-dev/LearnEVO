SELECT BKICMSTR.BKIC_PROD_CLASS as 'Class', 
       BKICMSTR.BKIC_PROD_CODE as 'Item', 
       BKICMSTR.BKIC_PROD_DESC as 'Description', 
       BKICMSTR.BKIC_PROD_UOH as 'On Hand', 
       BKICMSTR.BKIC_PROD_UOSO as 'On SO', 
       BKICMSTR.BKIC_PROD_UBO as 'On BO', 
       BKICMSTR.BKIC_PROD_UOO as 'On PO', 
       MTICMSTR.MTIC_PROD_UOA as 'Alloc', 
       MTICMSTR.MTIC_PROD_UOWO as 'On WO', 
       BKICMSTR.BKIC_PROD_AVGC as 'Avg Cost', 
       MIN(INVTXN.MTIT_DATE)  as '1st Used'
FROM   BKICMSTR, INVTXN, MTICMSTR
WHERE  BKICMSTR.BKIC_PROD_CODE = INVTXN.MTIT_CODE
AND    BKICMSTR.BKIC_PROD_CODE = MTICMSTR.MTIC_PROD_CODE
AND    BKICMSTR.BKIC_PROD_TYPE IN ('F', 'A', 'R', 'M')
AND    INVTXN.MTIT_TYPE IN ('I', 'S', 'J', 'M')
GROUP BY BKICMSTR.BKIC_PROD_CLASS, BKICMSTR.BKIC_PROD_CODE, BKICMSTR.BKIC_PROD_DESC, 
         BKICMSTR.BKIC_PROD_UOH, BKICMSTR.BKIC_PROD_UOSO, BKICMSTR.BKIC_PROD_UBO, 
         BKICMSTR.BKIC_PROD_UOO, BKICMSTR.BKIC_PROD_AVGC, MTICMSTR.MTIC_PROD_UOA, 
         MTICMSTR.MTIC_PROD_UOWO
