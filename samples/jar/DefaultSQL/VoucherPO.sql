SELECT BKAPINVL.BKAP_INVL_CODE, BKAPINVL.BKAP_INVL_DATE, BKAPINVL.BKAP_INVL_DAMT_1, 
       BKAPINVL.BKAP_INVL_GLACT_1, BKAPINVL.BKAP_INVL_DAMT_2, BKAPINVL.BKAP_INVL_GLACT_2
FROM   BKAPHPO, BKAPINVL
WHERE  BKAPINVL.BKAP_INVL_CODE IN
       (SELECT BKAPHPO.BKAP_PO_VNDCOD 
        FROM BKAPHPO)
AND    BKAPINVL.BKAP_INVL_DATE >= '2020-01-01'
ORDER BY BKAPINVL.BKAP_INVL_CODE ASC, BKAPINVL.BKAP_INVL_DATE ASC
