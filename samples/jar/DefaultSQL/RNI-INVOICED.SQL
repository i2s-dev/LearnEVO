SELECT BKAPINVT.BKAP_INVT_CODE, BKAPINVT.BKAP_INVT_PDATE, BKAPINVT.BKAP_INVT_AMT, 
       BKAPINVT.BKAP_INVT_DESC, BKAPINVT.BKAP_INVT_FRT, BKAPINVT.BKAP_INVT_TAX, 
       BKAPINVT.BKAP_INVT_TYPE
FROM   BKAPINVT
WHERE  SUBSTRING(BKAPINVT.BKAP_INVT_EXTRA,49,1) = 'R'
AND    BKAPINVT.BKAP_INVT_PDATE >= '2023-10-01'
AND    BKAPINVT.BKAP_INVT_PDATE <= '2023-10-31'
