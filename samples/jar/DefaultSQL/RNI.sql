SELECT BKAPHPO.BKAP_PO_NUM, BKAPHPO.BKAP_PO_VNDCOD, BKAPHPO.BKAP_PO_VNDNME, 
       BKAPHPOL.BKAP_POL_PCODE, BKAPHPOL.BKAP_POL_PPRCE, BKAPHPOL.BKAP_POL_RQTY, BKAPHPOL.BKAP_POL_INVNUM
FROM   BKAPHPO, BKAPHPOL
WHERE  BKAPHPO.BKAP_PO_NUM = BKAPHPOL.BKAP_POL_PONM
AND    BKAPHPO.BKAP_PO_RECNUM = BKAPHPOL.BKAP_POL_RECNUM
AND    BKAPHPOL.BKAP_POL_INVNUM < '1'
AND    BKAPHPOL.BKAP_POL_PCODE <> ''
AND    BKAPHPOL.BKAP_POL_RQTY <> 0
ORDER BY BKAPHPO.BKAP_PO_VNDNME ASC, BKAPHPO.BKAP_PO_NUM ASC